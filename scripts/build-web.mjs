// Turns `vite build --mode web` output into an installable web app for Cloudflare Pages: a manifest,
// a home-screen icon and a service worker that keeps every built file, so the app opens without
// internet after one visit and updates itself the next time there is signal.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { walk } from './files.mjs';

const dist = 'dist-web';
const indexPath = path.join(dist, 'index.html');
let html = fs.readFileSync(indexPath, 'utf8');

// Same cat as CatMark (src/components/icons.tsx), on a pink tile.
const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
<rect width="512" height="512" rx="112" fill="#f9d7e5"/>
<g transform="translate(86 120) scale(10)">
<path d="M3 26 L4 5 L11 12 L23 12 L30 5 L31 26 Q17 32 3 26Z" fill="#ffffff" stroke="#3a3540" stroke-width="1.8"/>
<circle cx="12" cy="18" r="1.6" fill="#3a3540"/><circle cx="22" cy="18" r="1.6" fill="#3a3540"/>
</g></svg>
`;
fs.writeFileSync(path.join(dist, 'icon.svg'), icon);

const manifest = {
  name: 'הגשמת חלום ביפן',
  short_name: 'יפן',
  lang: 'he',
  dir: 'rtl',
  start_url: './',
  scope: './',
  display: 'standalone',
  background_color: '#fffbfd',
  theme_color: '#eaf3fc',
  icons: [{ src: 'icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' }],
};
fs.writeFileSync(path.join(dist, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2));

html = html.replace(
  '</head>',
  `  <link rel="manifest" href="./manifest.webmanifest">
    <link rel="icon" href="./icon.svg" type="image/svg+xml">
    <link rel="apple-touch-icon" href="./icon.svg">
    <meta name="apple-mobile-web-app-capable" content="yes">
    <meta name="apple-mobile-web-app-title" content="יפן">
    <meta name="robots" content="noindex, nofollow">
  </head>`,
);
fs.writeFileSync(indexPath, html);

const precache = walk(dist)
  .map((file) => path.relative(dist, file).split(path.sep).join('/'))
  .filter((file) => !/^(sw\.js|_headers|japan-together-offline\.html)$/.test(file))
  .map((file) => (file === 'index.html' ? './' : `./${file}`))
  .sort();
assert.ok(precache.includes('./'), 'index.html missing from the precache list');

const hash = crypto.createHash('sha256');
for (const file of walk(dist).sort()) hash.update(fs.readFileSync(file));
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/build-web.mjs.
const CACHE = 'japan-${version}';
// List items' photos never change (a new photo gets a new id), so they are kept across updates.
const PHOTOS = 'japan-photos';
const FILES = ${JSON.stringify(precache)};
// On a weak signal a page request can hang for a long time; after this, the saved page is shown.
const NETWORK_MS = 3500;
const SAVED_PAGE = { ignoreSearch: true, ignoreVary: true };

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE && key !== PHOTOS).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (request.method === 'GET' && url.origin === self.location.origin && url.pathname.startsWith('/api/photo/')) {
    event.respondWith(
      caches.open(PHOTOS).then(async (cache) => {
        const hit = await cache.match(request);
        if (hit) return hit;
        const response = await fetch(request);
        if (response.ok) await cache.put(request, response.clone());
        return response;
      }),
    );
    return;
  }
  // The live changes must always come from the server (src/lib/liveSync.ts).
  if (request.method !== 'GET' || url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;
  if (request.mode === 'navigate') {
    // Fresh page when the network answers quickly, the saved one when it doesn't (or there is none).
    const network = fetch(request);
    network.catch(() => undefined);
    const slow = new Promise((resolve) => setTimeout(resolve, NETWORK_MS));
    event.respondWith(
      Promise.race([network, slow])
        .then(async (response) => response || (await caches.match('./', SAVED_PAGE)) || network)
        .catch(async () => (await caches.match('./', SAVED_PAGE)) || Response.error()),
    );
    return;
  }
  // Built files have hashed names, so a saved copy is always right.
  event.respondWith(
    caches.match(request, { ignoreVary: true }).then(
      (hit) =>
        hit ||
        fetch(request).then((response) => {
          if (response.ok) {
            const copy = response.clone();
            void caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;
fs.writeFileSync(path.join(dist, 'sw.js'), sw);

// Cloudflare: keep every file out of search engines, and always check for a new service worker
// and page.
fs.writeFileSync(
  path.join(dist, '_headers'),
  `/*
  X-Robots-Tag: noindex, nofollow
/sw.js
  Cache-Control: no-cache
/
  Cache-Control: no-cache
/index.html
  Cache-Control: no-cache
`,
);

console.log(`Web app: ${precache.length} files kept for offline (cache ${version}).`);
