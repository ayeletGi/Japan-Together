import { laundryEvents, laundryTags } from './laundry';
import { luggageEvents } from './luggage';
import raw from './trip-days.json';
import { liveChanges, onLiveChange, type EventChange, type LiveChanges } from './live';
import type { TripDay, TripEvent } from './types';
import { addDays, daysBetween, japanToday, toMinutes, wallClock, type TimeZone } from '../lib/time';
import { ISRAEL_TZ, JAPAN_TZ } from '../lib/time';

const START = '2037-11-02';
const END = '2037-11-18';

export const TRIP = {
  start: START,
  end: END,
  dayCount: daysBetween(START, END) + 1,
} as const;

/** The original meal notes point to a separate hours table; the meal card shows those hours itself. */
const HOURS_POINTER =
  / \| שעות הפעילות המדויקות וקישור לבדיקת עדכונים מופיעים באזור ״פתוח עד מתי\?״ ביום זה\.$/;

/**
 * All 17 days and 89 activities from the original plan, plus the laundry and luggage forwarding added
 * after it (`laundry.ts`, `luggage.ts`), with the later changes from `live.ts` on top: corrected titles,
 * times, notes and routes, removed activities and new ones.
 * The original part is generated by `scripts/sync-source.mjs`, which only removes document references
 * and booking numbers. Edit the private source and re-run it, or edit the JSON by hand with
 * evidence; `npm run audit:source` compares the two. Changes after the original plan go to the live
 * database instead (`npm run live`).
 */
function buildDays(changes: LiveChanges): TripDay[] {
  const added = Object.values(changes.added);
  return (raw as { days: TripDay[] }).days.map((day) => {
    const dayChange = changes.days[day.date] ?? {};
    const tags = laundryTags[day.date] ? [...day.tags, laundryTags[day.date]] : day.tags;
    const events = [
      ...day.events.map((event) => ({ ...event, note: event.note.replace(HOURS_POINTER, '') })),
      ...laundryEvents.filter((event) => event.date === day.date),
      ...luggageEvents.filter((event) => event.date === day.date),
      ...added.filter((event) => event.date === day.date),
    ];
    return {
      ...day,
      route: dayChange.route ?? day.route,
      headline: dayChange.headline ?? day.headline,
      tags: dayChange.extraTags ? [...tags, ...dayChange.extraTags] : tags,
      events: events
        .filter((event) => !changes.events[event.id]?.removed)
        .map((event) => applyEventChange(event, changes.events[event.id])),
    };
  });
}

function applyEventChange(event: TripEvent, change: EventChange | undefined): TripEvent {
  if (!change) return event;
  return {
    ...event,
    title: change.title ?? event.title,
    time: change.time !== undefined ? change.time : event.time,
    end: change.end !== undefined ? change.end : event.end,
    place: change.place ?? event.place,
    note: change.note ?? event.note,
    status: change.status ?? event.status,
  };
}

// Rebuilt in place, so every module that imported these sees the latest changes.
export const days: TripDay[] = [];
export const allEvents: TripEvent[] = [];
export const tripDates: string[] = [];
/** Activities hidden by a later change. */
export const REMOVED_EVENTS = new Set<string>();

function rebuild() {
  const changes = liveChanges();
  days.splice(0, days.length, ...buildDays(changes));
  allEvents.splice(0, allEvents.length, ...days.flatMap((day) => day.events));
  tripDates.splice(0, tripDates.length, ...days.map((day) => day.date));
  REMOVED_EVENTS.clear();
  for (const [id, change] of Object.entries(changes.events)) {
    if (change.removed) REMOVED_EVENTS.add(id);
  }
}
rebuild();
onLiveChange(rebuild);

export function getDay(date: string): TripDay | undefined {
  return days.find((day) => day.date === date);
}

export function getEvent(id: string): TripEvent | undefined {
  return allEvents.find((event) => event.id === id);
}

export function isTripDate(date: string): boolean {
  return tripDates.includes(date);
}

/**
 * The clock a day is lived by. The departure day happens in Israel (the flight leaves at 19:00
 * Israel time, when it is already the next day in Japan); every other day is lived in Japan.
 */
const dayZones: Record<string, TimeZone> = { [START]: ISRAEL_TZ };

export function dayTimeZone(date: string): TimeZone {
  return dayZones[date] ?? JAPAN_TZ;
}

/**
 * The trip day it is now: the first trip day that is today by its own clock, so the departure
 * day lasts until midnight in Israel. Outside the trip, today's date in Japan.
 */
export function tripToday(now: Date = new Date()): string {
  return (
    tripDates.find((date) => wallClock(now, dayTimeZone(date)).date === date) ?? japanToday(now)
  );
}

/** The day the app opens on: today during the trip, otherwise the first day. */
export function defaultDate(now: Date = new Date()): string {
  const today = tripToday(now);
  return isTripDate(today) ? today : TRIP.start;
}

export function neighbourDates(date: string): { previous?: string; next?: string } {
  const previous = addDays(date, -1);
  const next = addDays(date, 1);
  return {
    previous: isTripDate(previous) ? previous : undefined,
    next: isTripDate(next) ? next : undefined,
  };
}

/** The outbound flight is written in Israel time; everything else is Japan time. */
const eventZones: Record<string, TimeZone> = { 'd2-01': ISRAEL_TZ };

export function eventTimeZone(event: Pick<TripEvent, 'id'>): TimeZone {
  return eventZones[event.id] ?? JAPAN_TZ;
}

/**
 * The original plan lists untimed events last, so a check-out could appear after the check-in. These clocks only
 * place untimed events in a sensible order; they are never displayed as times.
 */
const untimedOrder: Record<string, string> = {
  'd3-02': '14:30',
  'd5-01': '09:00',
  'd6-04': '17:30',
  'd7-01': '09:00',
  'd8-01': '09:00',
  'd8-02': '11:00',
  'd9-06': '19:30',
  'd10-01': '08:00',
  'd10-02': '09:00',
  'd10-03': '09:01',
  'd11-01': '09:00',
  'd13-05': '17:00',
  'd14-01': '09:00',
  'd14-02': '20:50',
  'd15-01': '09:00',
  'd16-01': '08:05',
  'd16-02': '12:30',
  'shuttle-back-16': '21:00',
  'd17-01': '08:05',
  'd17-02': '12:30',
  'shuttle-back-17': '21:00',
  'd18-01': '09:00',
  'd18-02': '10:00',
};

export function sortKey(event: TripEvent): number {
  const clock = event.time ?? untimedOrder[event.id] ?? '23:59';
  return toMinutes(clock);
}

/** Events in the order the day is lived, without changing any stored time. */
export function orderedEvents(day: TripDay): TripEvent[] {
  return day.events
    .map((event, index) => ({ event, index }))
    .sort((a, b) => sortKey(a.event) - sortKey(b.event) || a.index - b.index)
    .map(({ event }) => event);
}
